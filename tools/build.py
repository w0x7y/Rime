def nvim_palette(spec):
    p = spec["palette"]
    body = "\n".join(f'  {k} = "{v}",' for k, v in p.items())
    return (f"-- {spec['name']}: {spec['description']}\n"
            "-- Generated by tools/build.py from palettes/" + spec["slug"] + ".json. Do not edit.\n"
            f"return {{\n  name = \"{spec['name']}\",\n{body}\n}}\n")


