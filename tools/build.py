def foot(spec):
    c = roles(spec)
    n = lambda h: h.lstrip("#")
    out = [header(spec), "# foot 1.26+; rename the section to [colors] for older versions", "[colors-dark]", f"foreground={n(c['fg'])}", f"background={n(c['bg'])}",
           f"selection-foreground={n(c['fg_bright'])}", f"selection-background={n(c['bg_sel'])}",
           f"urls={n(c['blue'])}"]
    out += [f"regular{i}={n(col)}" for i, col in enumerate(c["ansi"][:8])]
    out += [f"bright{i}={n(col)}" for i, col in enumerate(c["ansi"][8:])]
    out += [f"dim{i}={n(col)}" for i, col in enumerate(c["ansi_dim"])]
    return "\n".join(out) + "\n"


def windows_terminal(specs):
    schemes = []
    for spec in specs:
        c = roles(spec)
        names = ["black", "red", "green", "yellow", "blue", "purple", "cyan", "white"]
        s = {"name": spec["name"], "background": c["bg"], "foreground": c["fg"],
             "cursorColor": c["fg"], "selectionBackground": c["bg_sel"]}
        for i, nm in enumerate(names):
            s[nm] = c["ansi"][i]
            s["bright" + nm.capitalize()] = c["ansi"][i + 8]
        schemes.append(s)
    return json.dumps(schemes, indent=2) + "\n"


